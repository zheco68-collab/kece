CREATE TABLE IF NOT EXISTS `announcement` (
    `id`          BIGINT AUTO_INCREMENT PRIMARY KEY COMMENT '公告主键ID',
    `title`       VARCHAR(128) NOT NULL COMMENT '公告标题',
    `summary`     VARCHAR(255) NULL COMMENT '导读摘要（为空时截取正文前100字纯文本）',
    `content`     MEDIUMTEXT NOT NULL COMMENT 'Markdown格式正文内容',
    `author_name` VARCHAR(64) NOT NULL DEFAULT 'admin' COMMENT '发布主体管理员用户名',
    `is_pinned`   TINYINT NOT NULL DEFAULT 0 COMMENT '是否置顶：1-置顶，0-普通',
    `priority`    INT NOT NULL DEFAULT 0 COMMENT '排序权重（降序排列，数值越大越靠前）',
    `status`      VARCHAR(16) NOT NULL DEFAULT 'PUBLISHED' COMMENT '状态：PUBLISHED-已发布，DRAFT-草稿，ARCHIVED-已下架',
    `view_count`  INT NOT NULL DEFAULT 0 COMMENT '累计浏览阅读次数',
    `created_by`  BIGINT NOT NULL COMMENT '创建者管理员用户ID',
    `created_at`  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at`  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    KEY `idx_board_sort` (`status`, `is_pinned` DESC, `priority` DESC, `id` DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='平台系统公告与通知看板表';

